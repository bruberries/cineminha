// Pick the saved language, then the browser's, then Portuguese.
window.pickLang = (saved) => {
  if (saved && window.STRINGS[saved]) return saved;
  const nav = (navigator.language || '').slice(0, 2);
  return window.STRINGS[nav] ? nav : 'pt';
};
